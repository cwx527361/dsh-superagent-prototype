#!/bin/sh
# Install the dsh-runner CLI from a published channel manifest.
#
#   sh runner/install/install.sh https://<bucket>/channels/stable.json
#   DSH_RUNNER_CHANNEL=file:///abs/dist/channels/stable.json sh runner/install/install.sh
#
# The runner is a pure-Python CLI: this verifies the wheel's sha256 and hands
# it to `uv tool install`, which puts `dsh-runner` on PATH (~/.local/bin).
set -eu

CHANNEL=${1:-${DSH_RUNNER_CHANNEL:-}}
if [ -z "$CHANNEL" ]; then
	echo "usage: install.sh <channel-manifest-url>" >&2
	echo "  e.g. install.sh https://example.invalid/runner/channels/stable.json" >&2
	exit 2
fi

if ! command -v uv >/dev/null 2>&1; then
	echo "uv is required: https://docs.astral.sh/uv/getting-started/installation/" >&2
	exit 2
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

case "$CHANNEL" in
file://*) cp "${CHANNEL#file://}" "$TMP/channel.json" ;;
*) curl -fsSL "$CHANNEL" -o "$TMP/channel.json" ;;
esac

# Pure shell JSON reading: the manifest is generated by release.sh and flat.
VERSION=$(sed -n 's/^[[:space:]]*"version": "\([^"]*\)".*/\1/p' "$TMP/channel.json" | head -1)
NAME=$(sed -n 's/^[[:space:]]*{ "name": "\([^"]*\)".*/\1/p' "$TMP/channel.json" | head -1)
SUM=$(sed -n 's/.*"sha256": "\([0-9a-f]\{64\}\)".*/\1/p' "$TMP/channel.json" | head -1)
if [ -z "$VERSION" ] || [ -z "$NAME" ] || [ -z "$SUM" ]; then
	echo "malformed channel manifest: $CHANNEL" >&2
	exit 1
fi

BASE=${CHANNEL%/*}
URL="$BASE/releases/$VERSION/$NAME"
case "$CHANNEL" in
file://*) URL="$BASE/../releases/$VERSION/$NAME" ;;
esac

echo "installing dsh-runner $VERSION"
case "$URL" in
file://*) cp "${URL#file://}" "$TMP/$NAME" ;;
*) curl -fsSL "$URL" -o "$TMP/$NAME" ;;
esac

if command -v sha256sum >/dev/null 2>&1; then
	ACTUAL=$(sha256sum "$TMP/$NAME" | awk '{print $1}')
else
	ACTUAL=$(shasum -a 256 "$TMP/$NAME" | awk '{print $1}')
fi
if [ "$ACTUAL" != "$SUM" ]; then
	echo "sha256 mismatch for $NAME" >&2
	echo "  expected $SUM" >&2
	echo "  actual   $ACTUAL" >&2
	exit 1
fi

uv tool install --force "$TMP/$NAME"
BIN=$(uv tool dir --bin 2>/dev/null || true)
if [ -n "$BIN" ] && [ -x "$BIN/dsh-runner" ]; then
	"$BIN/dsh-runner" version
	echo "installed: $BIN/dsh-runner"
else
	echo "installed; add uv's bin dir to PATH if dsh-runner is not found" >&2
fi
echo "next: dsh-runner login --server <hub-url> --oauth"
